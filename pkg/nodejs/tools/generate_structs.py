"""Generate checked-in POD marshalling from the SDK's C header (no third-party modules)."""
from pathlib import Path
import argparse
import re
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT.parents[1] / "include/livekit/capi/livekit.h"

def camel(name):
    head, *tail = name.split("_")
    return head + "".join(part.title() for part in tail)

def typename(name):
    return "C" + "".join(part.title() for part in name.removeprefix("lk_").removesuffix("_t").split("_"))

BOOLS = set("enabled muted reliable recording dtx red simulcast auto_subscribe adaptive_stream dynacast echo_cancellation auto_gain_control noise_suppression include_cursor compress update deleted generated hidden recorder agent allow_all all_participants_allowed subscription_allowed backup_video_codec_enabled preconnect_buffer user_timestamp frame_id".split())

def is_bool(typ, name, struct):
    return typ == "int" and (name.startswith(("is_", "has_", "can_")) or name in BOOLS or (name == "user_data" and struct == "lk_frame_metadata_features_t") or name.endswith("_enabled") or name.endswith("_available"))

def generate():
    source = re.sub(r"/\*.*?\*/", "", HEADER.read_text(encoding="utf-8"), flags=re.S)
    structs = {}
    for _, body, name in re.findall(r"typedef struct (\w+)\s*\{(.*?)\}\s*(\w+);", source, re.S):
        fields = []
        for line in body.split(";"):
            line = " ".join(line.split())
            if not line:
                continue
            match = re.fullmatch(r"(.+?)(\w+)", line)
            if not match:
                raise ValueError(line)
            fields.append((match[1].strip(), match[2]))
        structs[name] = fields
    enums = {name: re.findall(r"(LK_\w+)\s*=\s*([^,]+)", body) for _, body, name in re.findall(r"typedef enum (\w+)\s*\{(.*?)\}\s*(\w+);", source, re.S)}
    inits = set(re.findall(r"LKC_API void (lk_\w+_init)\(", source))
    pack = ["// Generated by tools/generate_structs.py. Do not edit."]
    read = ["// Generated by tools/generate_structs.py. Do not edit."]
    ts = ["// Generated from include/livekit/capi/livekit.h. Do not edit.", '/// <reference types="node" />']
    schemas = {}
    for name in structs:
        pack.append(f"Value Pack(const {name}& v);")
        read.append(f"void Read(napi_env env, napi_value input, {name}& v, Arena& arena);")
    for struct, fields in structs.items():
        if struct == "lk_room_callbacks_t":
            continue
        skips = set()
        descriptors = []
        for index, (typ, name) in enumerate(fields):
            if name == "struct_size" or typ == "void*" or "callback" in typ or typ in {"lk_text_stream_handler", "lk_byte_stream_handler", "lk_reconnect_policy_callback"}:
                skips.add(name)
                continue
            count = None
            if "*" in typ and index + 1 < len(fields):
                nt, nn = fields[index + 1]
                if nt == "size_t" and (nn.endswith("count") or nn.endswith("size")):
                    count = nn
                    skips.add(nn)
            descriptors.append((typ, name, count))
        pack.append(f"Value Pack(const {struct}& v) {{\nObject out;")
        init = struct.removesuffix("_t") + "_init"
        read.append(f"void Read(napi_env env, napi_value input, {struct}& v, Arena& arena) {{")
        read.append("(void)arena;")
        read.append("RequireObject(env, input);")
        read.append(f"{init}(&v);" if init in inits else "v = {};")
        if init not in inits and any(name == "struct_size" for _, name in fields):
            read.append("v.struct_size = sizeof(v);")
        ts.append(f"export interface {typename(struct)} {{")
        schema = {}
        for typ, name, count in descriptors:
            if name in skips:
                continue
            key = camel(name)
            base = typ.replace("const", "").replace("*", "").strip()
            ptrs = typ.count("*")
            get = f'Get(env, input, "{key}")'
            if ptrs:
                if count and base in {"uint8_t", "int16_t"}:
                    pack.append(f'out["{key}"] = Copy(reinterpret_cast<const uint8_t*>(v.{name}), v.{count} * sizeof({base}));')
                    expr = f'arena.Buffer<{base}>(env, {get}, v.{count})'
                    tstype = "Uint8Array"
                elif count and base == "char" and ptrs == 1:
                    pack.append(f'out["{key}"] = std::string(v.{name} ? v.{name} : "", v.{name} ? v.{count} : 0);')
                    expr = f'arena.CountedString(env, {get}, v.{count})'
                    tstype = "string"
                elif count:
                    elem = f'Value(v.{name}[i])' if base in enums else f'Pack(v.{name}[i])' if base in structs else f'Value(v.{name}[i])'
                    if base in enums:
                        elem = f'Value(int(v.{name}[i]))'
                    pack.extend(["{ Array values;", f"for (size_t i = 0; i < v.{count}; ++i) values.push_back({elem});", f'out["{key}"] = std::move(values); }}'])
                    if base == "char":
                        expr = f'arena.StringArray(env, {get}, v.{count})'
                        tstype = "string[]"
                    else:
                        expr = f'arena.ArrayOf<{base}>(env, {get}, v.{count})'
                        tstype = f"{typename(base) if base in structs else 'number'}[]"
                elif base == "char":
                    pack.append(f'out["{key}"] = v.{name};')
                    expr = f'arena.KeepString(env, {get})'
                    tstype = "string"
                elif base in structs:
                    pack.append(f'out["{key}"] = v.{name} ? Pack(*v.{name}) : Value();')
                    expr = f'arena.One<{base}>(env, {get})'
                    tstype = typename(base)
                else:
                    raise ValueError((struct, typ, name))
                read.append(f'if (Has(env, input, "{key}")) v.{name} = {expr};')
            elif base in structs:
                pack.append(f'out["{key}"] = Pack(v.{name});')
                read.append(f'if (Has(env, input, "{key}")) Read(env, {get}, v.{name}, arena);')
                tstype = typename(base)
            else:
                boolean = is_bool(typ, name, struct)
                packed = f'bool(v.{name})' if boolean else f'int(v.{name})' if base in enums else f'double(v.{name})' if base in {"size_t", "float"} else f'v.{name}'
                pack.append(f'out["{key}"] = {packed};')
                expr = f'ReadBoolean(env, {get})' if boolean else f'ReadNumber<{base}>(env, {get})'
                read.append(f'if (Has(env, input, "{key}")) v.{name} = {expr};')
                tstype = "boolean" if boolean else "bigint" if base in {"int64_t", "uint64_t"} else "number"
            ts.append(f"  {key}?: {tstype};")
            schema[key] = tstype
        pack.append("return out;\n}")
        read.append("}")
        ts.append("}")
        schemas[typename(struct)] = schema
    # The room callback table is installed by hand with guaranteed ownership and exception guards.
    pack = [line for line in pack if line != "Value Pack(const lk_room_callbacks_t& v);"]
    read = [line for line in read if "void Read(napi_env env, napi_value input, lk_room_callbacks_t&" not in line]
    declarations = [line for line in read if line.endswith("Arena& arena);")]
    tests = ["// Generated: available only in LIVEKIT_NODE_TESTING builds."]
    for name in structs:
        if name != "lk_room_callbacks_t":
            tests.append(f'if (type == "{typename(name)}") {{ {name} value{{}}; Read(env, Get(env, args, "value"), value, arena); return Pack(value); }}')
    constants = {}
    for enum, entries in enums.items():
        prefix = enum.removesuffix("_t").upper() + "_"
        name = typename(enum)[1:]
        values = {}
        for key, expression in entries:
            if not key.startswith(prefix):
                # RPC errors and some policy enums use a shorter constant prefix.
                import os
                prefix = os.path.commonprefix([key for key, _ in entries]).rsplit("_", 1)[0] + "_"
                break
        for key, expression in entries:
            value = eval(expression.replace("ULL", "").strip(), {"__builtins__": {}}, {})
            member = "".join(part.title() for part in key.removeprefix(prefix).split("_"))
            if member[0].isdigit():
                member = ("R" if name == "VideoRotation" else "N") + member
            values[member] = value
        constants[name] = values
    js = ["'use strict';", "// Generated by tools/generate_structs.py."]
    cts = ["// Generated by tools/generate_structs.py."]
    for name, values in constants.items():
        js.append(f"exports.{name} = Object.freeze({json.dumps(values)});")
        cts.append(f"export const {name}: Readonly<{{" + "; ".join(f"{key}: {value}" for key, value in values.items()) + "}>;")
    return {ROOT / "src/struct_pack.inc": "\n".join(pack) + "\n", ROOT / "src/struct_read.inc": "\n".join(read) + "\n", ROOT / "src/struct_read_decls.inc": "\n".join(declarations) + "\n", ROOT / "src/test_structs.inc": "\n".join(tests) + "\n", ROOT / "lib/capi-types.d.ts": "\n".join(ts) + "\n", ROOT / "lib/struct-schema.json": json.dumps(schemas, indent=2) + "\n", ROOT / "lib/constants.js": "\n".join(js) + "\n", ROOT / "lib/constants.d.ts": "\n".join(cts) + "\n"}

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if path.suffix == '.inc':
            content = subprocess.run(['clang-format', '--assume-filename=' + str(ROOT / 'src/generated.cpp')], input=content, text=True, capture_output=True, check=True).stdout
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated file: {path}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
